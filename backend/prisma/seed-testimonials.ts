// ─── Main ────────────────────────────────────────────────────────────────────

async function main() {
  console.log('🌱  Seeding testimonials...');

  for (const group of TESTIMONIALS) {
    const product = await prisma.product.findUnique({ where: { slug: group.productSlug } });
    if (!product) {
      console.warn(`⚠️  Product not found: ${group.productSlug} — skipping`);
      continue;
    }

    for (const item of group.items) {
      const t = await prisma.testimonial.create({
        data: {
          name:     item.name,
          role:     item.role,
          content:  item.content,
          rating:   item.rating,
          featured: item.featured,
          active:   true,
          sortOrder: 0,
        },
      });

      await prisma.productTestimonial.create({
        data: { productId: product.id, testimonialId: t.id },
      });
    }

    console.log(`✓  ${group.productSlug} — ${group.items.length} testimonial(s)`);
  }

  console.log('✅  seed-testimonials.ts complete.');
}

