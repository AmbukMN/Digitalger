// ─── Helper functions ────────────────────────────────────────────────────────

async function addFAQs(productId: string, items: { q: string; a: string }[], category: string) {
  for (let i = 0; i < items.length; i++) {
    const faq = await prisma.fAQ.create({
      data: { question: items[i].q, answer: items[i].a, category, active: true, sortOrder: i + 1 },
    });
    await prisma.productFAQ.create({ data: { productId, faqId: faq.id, sortOrder: i + 1 } });
  }
}

async function addBonus(productId: string) {
  const bundle = await prisma.productBundle.create({
    data: {
      productId,
      title: '🎁 Бонус файлууд — үнэгүй',
      description: 'Бүх худалдан авагчдад автоматаар ирдэг 6 нэмэлт загвар',
      sortOrder: 99,
    },
  });
  for (let i = 0; i < BONUS_FILES.length; i++) {
    await prisma.bundleItem.create({ data: { bundleId: bundle.id, name: BONUS_FILES[i], sortOrder: i } });
  }
}

async function addBundle(
  productId: string,
  title: string,
  description: string,
  sortOrder: number,
  items: string[],
) {
  const bundle = await prisma.productBundle.create({ data: { productId, title, description, sortOrder } });
  for (let i = 0; i < items.length; i++) {
    await prisma.bundleItem.create({ data: { bundleId: bundle.id, name: items[i], sortOrder: i } });
  }
}

