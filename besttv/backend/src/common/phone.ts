/** Монголын гар утасны эхний орон (оператор бүрийн блок) */
const MN_MOBILE_FIRST = /^[5-9]/;

/**
 * Дугаарыг 8 оронтой каноник хэлбэрт оруулна.
 *
 * Хүлээж авах хэлбэрүүд (бүгд ижил үр дүн → `99001122`):
 *   99001122 · 9900 1122 · 9900-1122 · +97699001122 · 97699001122
 *   0097699001122 · (976) 9900-1122
 *
 * @returns нормалчилсан 8 оронтой дугаар, эсвэл буруу бол `null`
 */
export function normalizePhone(raw: string | null | undefined): string | null {
  if (!raw) return null;

  /* Тоо биш БҮХ тэмдэгтийг хасна — зай, зураас, хаалт, «+» */
  let d = String(raw).replace(/\D/g, '');
  if (!d) return null;

  /* Олон улсын угтварыг арилгана: 00976… → 976… */
  if (d.startsWith('00')) d = d.slice(2);

  /**
   * ⚠️ «976»-г зөвхөн УРТ нь тохирох үед хасна.
   * `976` эхэлсэн 8 оронтой дугаар (ж: 97612345) нь БОДИТ дугаар байж
   * болно — шалгалтгүй хасвал 5 орон үлдэж эвдэрнэ.
   */
  if (d.length === 11 && d.startsWith('976')) d = d.slice(3);

  if (d.length !== 8) return null;
  /* Монголын гар утас 5-9-өөр эхэлнэ (1-4 нь суурин/тусгай дугаар) */
  if (!MN_MOBILE_FIRST.test(d)) return null;

  return d;
}

/** Хүнд харагдах хэлбэр — «9900-1122» */
export function formatPhone(phone: string | null | undefined): string {
  const n = normalizePhone(phone);
  return n ? `${n.slice(0, 4)}-${n.slice(4)}` : (phone ?? '');
}
