/**
 * SRT → WebVTT ХӨРВҮҮЛЭГЧ.
 *
 * ⚠️⚠️ ЗААВАЛ ХЭРЭГТЭЙ: браузер `.srt`-г ОГТ уншдаггүй. `<track>`
 * элемент нь зөвхөн WebVTT дэмждэг тул `.srt` шууд өгвөл хадмал
 * ЧИМЭЭГҮЙ гарахгүй (алдаа ч өгөхгүй — оношлоход хэцүү).
 *
 * Хоёр форматын ялгаа:
 *   SRT:  `WEBVTT` толгойгүй · цаг нь `00:00:01,500` (ТАСЛАЛ)
 *   VTT:  `WEBVTT` толгой ЗААВАЛ · цаг нь `00:00:01.500` (ЦЭГ)
 */

/** Хөрвүүлэлтийн үр дүн — админд тайлагнахад */
export interface SrtConvertResult {
  vtt: string;
  /** Хэдэн хадмалын блок танигдсан */
  cues: number;
}

/**
 * ⚠️ BOM (Byte Order Mark) — Windows дээр Notepad-аар хадгалсан файлд
 * түгээмэл. Хасахгүй бол ЭХНИЙ хадмалын дугаар танигдахгүй.
 */
const BOM = '﻿';

/**
 * `.srt` (эсвэл аль хэдийн `.vtt`) агуулгыг WebVTT болгоно.
 *
 * @throws агуулга нь хадмал биш бол (0 блок танигдсан)
 */
export function srtToVtt(raw: string): SrtConvertResult {
  let text = raw;

  /* BOM хасна */
  if (text.startsWith(BOM)) text = text.slice(1);

  /**
   * ⚠️ Мөрийн төгсгөлийг нэгтгэнэ. SRT нь ихэвчлэн Windows (`\r\n`)
   * боловч Mac/Linux-ээс ирсэн ч байж болно. `\r` үлдвэл цагийн
   * regex таарахгүй.
   */
  text = text.replace(/\r\n?/g, '\n').trim();

  /* Аль хэдийн VTT бол — зөвхөн цэвэрлээд буцаана */
  const alreadyVtt = /^WEBVTT/.test(text);

  /**
   * ⚠️⚠️ ЦАГИЙН ТАСЛАЛ → ЦЭГ. Энэ бол хамгийн ЧУХАЛ хөрвүүлэлт.
   * `00:00:01,500` (SRT) → `00:00:01.500` (VTT)
   *
   * ⚠️ Зөвхөн ЦАГИЙН МӨРӨНД солино — хадмалын ТЕКСТ доторх таслалыг
   * хөндөхгүй («Сайн уу, Болд» гэдэг «Сайн уу. Болд» болох ёсгүй).
   */
  text = text.replace(
    /(\d{1,2}:\d{2}:\d{2}),(\d{1,3})\s*-->\s*(\d{1,2}:\d{2}:\d{2}),(\d{1,3})/g,
    '$1.$2 --> $3.$4',
  );

  /**
   * ⚠️ Цаг нь `MM:SS,mmm` (цаггүй) хэлбэрээр ирж болно — зарим
   * хөрвүүлэгч ингэж бичдэг. VTT нь үүнийг зөвшөөрдөг ч
   * тогтвортой байлгахын тулд `00:` нэмнэ.
   */
  text = text.replace(
    /^(\d{1,2}:\d{2}[.,]\d{1,3})\s*-->\s*(\d{1,2}:\d{2}[.,]\d{1,3})/gm,
    (_m, a: string, b: string) => `00:${a.replace(',', '.')} --> 00:${b.replace(',', '.')}`,
  );

  /* Хэдэн блок байгааг тоолно — 0 бол хадмал БИШ */
  const cues = (text.match(/-->/g) ?? []).length;
  if (cues === 0) {
    throw new Error('Хадмалын файл танигдсангүй (цагийн мөр олдсонгүй)');
  }

  /**
   * ⚠️ Дугаарлалтын мөрийг ХАСАХГҮЙ — VTT нь cue-ийн ID болгон
   * зөвшөөрдөг. Хасах гэж оролдвол хадмалын текст санамсаргүй
   * устах эрсдэлтэй (зөвхөн тооноос бүрдсэн мөр байж болно).
   */

  if (!alreadyVtt) {
    /* ⚠️ `WEBVTT` толгой ЗААВАЛ — байхгүй бол браузер татгалзана.
       Дараа нь ХОЁР мөр таслах ёстой (стандартын шаардлага). */
    text = `WEBVTT\n\n${text}`;
  }

  /* ⚠️ Төгсгөлд мөр таслалт — зарим тоглуулагч сүүлийн блокыг
     алгасдаг */
  return { vtt: `${text}\n`, cues };
}

/** Дэмжигдэх хэлүүд — админ цэсэнд ба шалгалтад */
export const SUBTITLE_LANGS = [
  { code: 'mn', label: 'Монгол' },
  { code: 'en', label: 'English' },
  { code: 'ko', label: '한국어' },
  { code: 'ja', label: '日本語' },
  { code: 'zh', label: '中文' },
  { code: 'ru', label: 'Русский' },
] as const;

export type SubtitleLang = (typeof SUBTITLE_LANGS)[number]['code'];

export function subtitleLabel(code: string): string {
  return SUBTITLE_LANGS.find((l) => l.code === code)?.label ?? code.toUpperCase();
}
