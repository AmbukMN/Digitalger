async function main() {
  console.log('Демо контент оруулж байна...');

  // ── Блог ──
  let posts = 0;
  for (const p of POSTS) {
    const exists = await prisma.blogPost.findUnique({ where: { slug: p.slug } });
    if (exists) continue;
    await prisma.blogPost.create({
      data: {
        ...p,
        publishedAt: new Date(),
        metaTitle: p.title,
        metaDescription: p.excerpt,
      },
    });
    posts++;
  }

  // ── FAQ ──
  let faqs = 0;
  for (const f of FAQS) {
    const exists = await prisma.faq.findFirst({ where: { question: f.question } });
    if (exists) continue;
    await prisma.faq.create({ data: f });
    faqs++;
  }

  console.log(`Блог: ${posts} нэмэгдсэн (${POSTS.length}-аас)`);
  console.log(`FAQ:  ${faqs} нэмэгдсэн (${FAQS.length}-аас)`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
