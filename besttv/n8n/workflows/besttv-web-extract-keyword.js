/**
 * ⚠️⚠️ FAQ мөн эсэхийг ЗӨВХӨН ГОЛ АГУУЛГААР шийднэ.
 *
 * Хуучин `indexOf` арга нь «Намайг аварсан хайр ҮЗЭХ»-ийг FAQ гэж
 * андуурдаг байв. Одоо: FAQ хэллэгийг хассаны дараа УТГАТАЙ үг
 * үлдэж байвал энэ нь FAQ БИШ — киноны хайлт.
 */
function isFaqOnly(text) {
  var t = norm(text);
  if (!t) return true;

  /* Мэндчилгээ — ЯГ тэнцэл эсвэл маш богино */
  for (var i = 0; i < SMALL_TALK.length; i++) {
    if (t === SMALL_TALK[i]) return true;
  }

  /**
   * ⚠️⚠️ ЗӨВХӨН ТООНООС бүрдсэн бол ХАЙЛТ мөн — FAQ БИШ!
   *
   * БОДИТ АЛДАА: «99» гэж бичихэд `t.length <= 4` шалгуурт орж
   * «FAQ» гэж ангилагдаад хайлт ОГТ хийгддэггүй байв.
   *
   * Хэрэглэгчид кинонд ХОЧ өгдөг: «Өнчин охин» → «99», «999».
   * Админ эдгээрийг системд бүртгэсэн байдаг (Чат түлхүүр хуудас).
   *
   * ⚠️ Тоо нь мэндчилгээ БАЙЖ ЧАДАХГҮЙ тул онцгойлон зөвшөөрнө.
   */
  if (/^[0-9]+$/.test(t)) return false;

  if (t.length <= 4) return true;

  /* FAQ хэллэг олдвол ХАСААД үлдэгдлийг шалгана */
  var rest = t;
  var matched = false;
  for (var j = 0; j < FAQ_PHRASES.length; j++) {
    if (rest.indexOf(FAQ_PHRASES[j]) !== -1) {
      rest = rest.split(FAQ_PHRASES[j]).join(' ');
      matched = true;
    }
  }
  if (!matched) return false;

  /* Дагавар үгсийг ч хасна */
  for (var k = 0; k < TAIL_WORDS.length; k++) {
    rest = rest.split(TAIL_WORDS[k]).join(' ');
  }
  rest = rest.replace(/\s+/g, ' ').trim();

  /**
   * ⚠️ FAQ-ийн язгуур үгсийг ч хасна — «төлбөрӨӨ яаж төлөх» гэх
   * нөхцөлтэй хэлбэрүүд үлдэгдэлд орж, FAQ-ийг кино гэж
   * андуурахаас сэргийлнэ.
   */
  var FAQ_STEMS = ['төлбөр', 'багц', 'үнэ', 'купон', 'данс', 'имэйл',
    'нууц', 'бүртгэл', 'төхөөрөмж', 'тусламж', 'админ', 'хямдрал',
    /* ⚠️ ЛАТИН язгуур — «tuslamj hereqtei» гэх үлдэгдлийг ч шүүнэ */
    'tulbur', 'bagts', 'une', 'kupon', 'dans', 'email', 'imeil',
    'nuuts', 'burtgel', 'tuhuurumj', 'tuslamj', 'admin', 'hyamdral',
    'holboo', 'holbogd', 'password', 'yarih', 'hereg', 'hereq',
    'martsan', 'sergee', 'tatah', 'tataj'];
  var rw = rest.split(' ').filter(function (w) {
    if (w.length < 3) return false;
    for (var si = 0; si < FAQ_STEMS.length; si++) {
      /* Язгуураар эхэлж байвал FAQ-ийн үг гэж үзнэ */
      if (w.indexOf(FAQ_STEMS[si]) === 0) return false;
    }
    return true;
  });

  /**
   * ⚠️ Үлдэгдэлд утгатай үг байвал энэ нь FAQ БИШ —
   * киноны нэр хавсарсан гэсэн үг («багц хэд вэ, Хар жагсаалт бий юу»)
   */
  return rw.length === 0;
}

/** Киноны нэр болгож цэвэрлэх — дагавар, төрлийн үг хасна */
function cleanQuery(text) {
  var t = norm(text);
  for (var i = 0; i < TAIL_WORDS.length; i++) {
    /* ⚠️ Үгийн ХИЛЭЭР хасна — «үзэх» нь «үзэсгэлэн»-г эвдэхгүй */
    t = t.split(' ').filter(function (w) { return w !== TAIL_WORDS[i]; }).join(' ');
  }
  /* Олон үгтэй дагаврыг мөрөөр нь хасна */
  for (var j = 0; j < TAIL_WORDS.length; j++) {
    if (TAIL_WORDS[j].indexOf(' ') !== -1) t = t.split(TAIL_WORDS[j]).join(' ');
  }
  return t.replace(/\s+/g, ' ').trim();
}

